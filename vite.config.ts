/// <reference types="vitest/config" />
import react from '@vitejs/plugin-react';
import { defineConfig } from 'vite';
import { VitePWA } from 'vite-plugin-pwa';

// Base path: set VITE_BASE=/repo-name/ when deploying under a sub-path (e.g. GitHub Pages).
const base = process.env.VITE_BASE ?? '/';

// The Web App Manifest spec allows dir: "auto" (the UI switches between English and Hebrew at runtime),
// but vite-plugin-pwa's ManifestOptions type only lists "ltr" | "rtl"; the emitted JSON is still "auto".
const manifestDir = 'auto' as string as 'ltr' | 'rtl';

export default defineConfig({
  base,
  plugins: [
    react(),
    VitePWA({
      // A new build takes over silently; the fresh version shows on the next launch (src/lib/pwa.ts).
      registerType: 'autoUpdate',
      // Public files not referenced from the bundle but still needed offline. Manifest icons are
      // precached automatically. The icon set is generated by `npm run icons` (scripts/make-icons.mjs).
      includeAssets: ['favicon.svg', 'icon.svg', 'apple-touch-icon.png'],
      manifest: {
        name: 'Imposter',
        short_name: 'Imposter',
        description: 'Pass-the-phone party game: one secret word, one bluffer.',
        start_url: base,
        scope: base,
        display: 'standalone',
        orientation: 'portrait',
        background_color: '#0b0d12',
        theme_color: '#0b0d12',
        lang: 'en',
        dir: manifestDir,
        categories: ['games'],
        icons: [
          { src: 'icons/icon-192.png', sizes: '192x192', type: 'image/png' },
          { src: 'icons/icon-512.png', sizes: '512x512', type: 'image/png', purpose: 'any' },
          { src: 'icons/icon-512-maskable.png', sizes: '512x512', type: 'image/png', purpose: 'maskable' },
        ],
      },
      workbox: {
        // Precache the whole build: word packs are static JSON imports bundled into the JS, so after the
        // first visit no round ever needs the network (BRIEF US-12).
        globPatterns: ['**/*.{js,css,html,svg,png,ico,webmanifest,json,woff2}'],
        // SPA navigation (deep links, refresh mid-round) is answered from the cached shell, under the base.
        navigateFallback: `${base}index.html`,
        cleanupOutdatedCaches: true,
        // Bundled word packs make the main chunk larger than Workbox's 2 MiB default.
        maximumFileSizeToCacheInBytes: 5 * 1024 * 1024,
      },
    }),
  ],
  test: {
    environment: 'node',
    include: ['src/**/*.test.{ts,tsx}'],
  },
});
